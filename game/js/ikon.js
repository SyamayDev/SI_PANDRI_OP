  // Piksel yang berderet dalam satu baris digabung menjadi satu persegi panjang
  function ikon(nama, kelas = '') {
    const g = GRID[nama];
    if (!g) return '';
    let isi = '';
    g.forEach((baris, y) => {
      for (let x = 0; x < baris.length;) {
        const c = baris[x];
        if (c === '.') { x++; continue; }
        let w = 1;
        while (baris[x + w] === c) w++;
        isi += `<rect${c === 'o' ? ' class="a"' : ''} x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      }
    });
    return `<svg class="ikon${kelas ? ' ' + kelas : ''}" viewBox="0 0 ${g[0].length} ${g.length}" aria-hidden="true" focusable="false" shape-rendering="crispEdges" fill="currentColor">${isi}</svg>`;
  }
  window.IKON = ikon;
